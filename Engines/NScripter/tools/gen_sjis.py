"""Writes core/sjis_table.inc: the Unicode code point of every two-byte CP932 character, and of the one-byte
half-width katakana. Run with: python3 -I Engines/NScripter/tools/gen_sjis.py > <target>/core/sjis_table.inc"""
print('// Generated by Engines/NScripter/tools/gen_sjis.py from Python\'s cp932 codec. Do not edit.')
print('// Index: (lead - 0x81 or lead - 0xE0 + 31) * 192 + (trail - 0x40). 0 means unmapped.')
rows = []
for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
    row = []
    for trail in range(0x40, 0x100):
        try:
            ch = bytes([lead, trail]).decode('cp932')
            row.append(ord(ch) if len(ch) == 1 else 0)
        except UnicodeDecodeError:
            row.append(0)
    rows.append(row)
print('static const unsigned short kSjisTable[%d] = {' % (len(rows) * 192))
for row in rows:
    print('    ' + ','.join(str(v) for v in row) + ',')
print('};')
