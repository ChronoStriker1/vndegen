# Turns the extracted RPG class facts into Ruby class definitions, superclasses and outer classes first.
import sys
rows = []
for line in open(sys.argv[1]):
    cls, sup, attrs, inits = line.rstrip('\n').split('|', 3)
    if sys.argv[2:] and cls == 'RPG::Item' and not sup: cls = 'RPG::BaseItem'  # the VX help's typo
    rows.append((cls, sup.strip() or None, [a for a in attrs.split(',') if a], [kv.split('=', 1) for kv in inits.split(' ;; ') if kv]))
names = {r[0] for r in rows}
done, order = set(), []
def visit(r):
    if r[0] in done: return
    deps = []
    if r[1] in names: deps.append(r[1])
    outer = r[0].rsplit('::', 1)[0]
    if outer in names: deps.append(outer)
    for d in deps: visit(next(x for x in rows if x[0] == d))
    done.add(r[0]); order.append(r)
for r in rows: visit(r)
print('# Generated by tools from the RPG data classes the RGSS help documents: their attributes and initial values.')
print('module RPG')
for cls, sup, attrs, inits in order:
    short = cls[len('RPG::'):]
    print(f"  class {short}{' < ' + sup if sup else ''}")
    print('    def initialize')
    if sup: print('      super')
    for k, v in inits: print(f'      @{k} = {v.strip()}')
    print('    end')
    own = [a for a in attrs]
    if own: print('    attr_accessor ' + ', '.join(':' + a for a in own))
    print('  end')
print('end')
