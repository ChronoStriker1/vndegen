#!/usr/bin/env python3
"""Writes the CRGSS target's core/prelude.c from the Ruby files in ruby/, which the runtime evaluates when a game starts.

SwiftPM can't run build steps for C targets, so the output is checked in. Run this after changing a file in ruby/.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
ruby = root / 'ruby'
package = root.parent.parent / 'Packages' / 'VNDegenKit' / 'Sources' / 'CRGSS' / 'core'
# Each prelude and the files it joins, in order.
preludes = {
    'boot': ['boot.rb'],
    'common': ['common.rb'],
    'win32api': ['win32api.rb'],
    'rpg1': ['rpg1_data.rb', 'rpg1.rb'],
    'rpg2': ['rpg2_data.rb', 'rpg2.rb'],
    'rpg3': ['rpg3_data.rb', 'rpg3.rb'],
}


def c_string(text: bytes) -> str:
    lines = []
    for line in text.split(b'\n'):
        escaped = ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92, 63) else f'\\{b:03o}' for b in line + b'\n')
        lines.append(f'    "{escaped}"')
    return '\n'.join(lines)


out = ['// Generated by tools/embed.py from ruby/. Do not edit.', '#include "prelude.h"', '']
for name, files in preludes.items():
    text = b''.join((ruby / f).read_bytes() for f in files if (ruby / f).exists())
    out.append(f'const char rgss_prelude_{name}[] =\n{c_string(text)};\n')
(package / 'prelude.c').write_text('\n'.join(out))
header = ['// The Ruby files the runtime evaluates, from ruby/ (tools/embed.py).', '#ifndef RGSS_PRELUDE_H',
          '#define RGSS_PRELUDE_H', '']
header += [f'extern const char rgss_prelude_{name}[];' for name in preludes]
header += ['', '#endif', '']
(package / 'prelude.h').write_text('\n'.join(header))
