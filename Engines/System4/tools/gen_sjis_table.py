# Writes src/util/sjis_table.inc, the CP932 (Windows Shift-JIS) to Unicode table, from Python's
# cp932 codec, which implements Microsoft's CP932 mapping as published by the Unicode Consortium.
import os
here = os.path.dirname(os.path.abspath(__file__))
leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
rows = []
for lead in leads:
    vals = []
    for trail in range(0x40, 0x100):
        try:
            ch = bytes([lead, trail]).decode('cp932')
            vals.append(ord(ch) if len(ch) == 1 else 0)
        except UnicodeDecodeError:
            vals.append(0)
    rows.append(vals)
with open(os.path.join(here, '..', 'src', 'util', 'sjis_table.inc'), 'w') as f:
    f.write('// Generated by tools/gen_sjis_table.py. Rows are lead bytes 0x81-0x9F and 0xE0-0xFC,\n')
    f.write('// columns trail bytes 0x40-0xFF; 0 marks an unmapped pair.\n')
    for vals in rows:
        f.write('{' + ','.join('0x%X' % v for v in vals) + '},\n')
