struct OpInfo {
    const char *name;
    int8_t args;  // -1 marks numbers no test game uses
};

constexpr int kOpCount = 258;
extern const OpInfo kOps[kOpCount];

inline const OpInfo *opInfo(uint16_t op) { return op < kOpCount && kOps[op].args >= 0 ? &kOps[op] : nullptr; }

