#define SYS_GLOBALS_AT 64
#define SYS_GLOBALS 2000
#define REC_SIZE 196
#define REC_TIMES 47

static size_t encoded_size(size_t n) { return ((n + 255) >> 8) * 273 + 1; }

static u8 *decode(const u8 *in, size_t n, size_t *outSize) {
    if (n < 1 || (n - 1) % 273) return NULL;
    size_t blocks = (n - 1) / 273;
    u8 *out = pj_alloc(blocks * 256 + 1);
    u32 s = (u8)(in[0] - 0x93);
    const u8 *p = in + 1;
    u8 *o = out;
    for (size_t b = 0; b < blocks; b++) {
        u8 total = 0;
        for (int r = 0; r < 16; r++) {
            u8 sum = 0;
            for (int c = 0; c < 16; c++) {
                o[c] = (u8)(p[c] - key[s + c] - key[0x80 + s + r]);
                sum = (u8)(sum + o[c]);
            }
            if ((u8)(key[s + r] + sum) != p[16]) {
                free(out);
                return NULL;
            }
            total = (u8)(total + sum);
            s = (u8)(s + sum);
            o += 16;
            p += 17;
        }
        if (*p++ != total) {
            free(out);
            return NULL;
        }
    }
    *outSize = blocks * 256;
    return out;
}

static u8 *encode(const u8 *in, size_t n, u32 seed, size_t *outSize) {
    size_t padded = (n + 255) & ~(size_t)255;
    u8 *plain = pj_alloc(padded ? padded : 1);
    memcpy(plain, in, n);
    u8 *out = pj_alloc(encoded_size(n));
    u32 s = seed & 255;
    out[0] = (u8)(s + 0x93);
    u8 *o = out + 1;
    const u8 *q = plain;
    for (size_t b = 0; b < padded / 256; b++) {
        u8 total = 0;
        for (int r = 0; r < 16; r++) {
            u8 sum = 0;
            for (int c = 0; c < 16; c++) {
                o[c] = (u8)(q[c] + key[s + c] + key[0x80 + s + r]);
                sum = (u8)(sum + q[c]);
            }
            o[16] = (u8)(key[s + r] + sum);
            total = (u8)(total + sum);
            s = (u8)(s + sum);
            o += 17;
            q += 16;
        }
        *o++ = total;
    }
    free(plain);
    *outSize = encoded_size(n);
    return out;
}

static u8 *load_file(PJ *p, const char *name, size_t *size) {
    char *path = pj_fmt("%s/%s", p->saveDir, name);
    size_t n;
    u8 *raw = pj_read_file(path, &n);
    free(path);
    if (!raw) return NULL;
    u8 *plain = decode(raw, n, size);
    free(raw);
    if (!plain) pj_log(p, "%s doesn't decode", name);
    return plain;
}

static bool store_file(PJ *p, const char *name, const u8 *plain, size_t n) {
    size_t size;
    u8 *enc = encode(plain, n, pj_rand(p), &size);
    pj_mkdirs(p->saveDir);
    char *path = pj_fmt("%s/%s", p->saveDir, name);
    bool ok = pj_write_file(path, enc, size);
    if (!ok) pj_log(p, "can't write %s", path);
    free(path);
    free(enc);
    return ok;
}

static u8 *record(PJ *p, int id, bool create) {
    if (!p->recs) return NULL;
    for (size_t at = 16; at + REC_SIZE <= p->recsSize; at += REC_SIZE) {
        u8 *r = p->recs + at;
        if (rd32(r) == 0) {
            if (!create) return NULL;
            wr32(r, 2);
            wr32(r + 4, (u32)id);
            return r;
        }
        if ((int)rd32(r + 4) == id) return r;
    }
    return NULL;
}

bool pj_stage_cleared(PJ *p, int chapter, int stage) {
    const u8 *r = record(p, chapter * 10 + stage, false);
    return r && rd32(r) == 2;
}

int pj_stage_best(PJ *p, int chapter, int stage) {
    const u8 *r = record(p, chapter * 10 + stage, false);
    int best = -1;
    for (int i = 0; r && i < REC_TIMES; i++) {
        int t = (int)rd32(r + 8 + 4 * i);
        if (t > 0 && t - 1 > best) best = t - 1;
    }
    return best;
}

void pj_stage_record(PJ *p, int chapter, int stage, int seconds) {
    u8 *r = record(p, chapter * 10 + stage, true);
    if (!r) return;
    wr32(r, 2);
    for (int i = 0; i < REC_TIMES; i++)
        if (rd32(r + 8 + 4 * i) == 0) {
            wr32(r + 8 + 4 * i, (u32)(seconds + 1));
            return;
        }
}

static void fresh_system(PJ *p) {
    p->sysSize = 19200;
    p->sys = pj_alloc(p->sysSize);
    memcpy(p->sys, "PJSYSDAT_Rev1.00", 16);
    wr32(p->sys + 16, SYS_GLOBALS * 4);
    wr32(p->sys + 20, 72);
    wr32(p->sys + 24, 68);
    wr32(p->sys + 32, 128);
}

static void fresh_records(PJ *p) {
    u32 body = 0x4fe20;
    p->recsSize = 16 + body;
    p->recs = pj_alloc(p->recsSize);
    memcpy(p->recs, "POPLAYDT", 8);
    wr32(p->recs + 8, body);
}

bool pj_save_load(PJ *p) {
    size_t n;
    u8 *sys = load_file(p, "syssave.dat", &n);
    if (sys && n >= SYS_GLOBALS_AT + SYS_GLOBALS * 4 && !memcmp(sys, "PJSYSDAT_Rev1.00", 16)) {
        p->sys = sys;
        p->sysSize = n;
        for (int i = 0; i < SYS_GLOBALS && i < PJ_GLOBALS; i++) p->g[i] = (i32)rd32(sys + SYS_GLOBALS_AT + 4 * i);
    } else {
        free(sys);
        fresh_system(p);
    }
    u8 *recs = load_file(p, "syssvpo.dat", &n);
    if (recs && n >= 16 && !memcmp(recs, "POPLAYDT", 8) && 16 + (size_t)rd32(recs + 8) <= n) {
        p->recs = recs;
        p->recsSize = 16 + rd32(recs + 8);
    } else {
        free(recs);
        fresh_records(p);
    }
    pj_log(p, "loaded system save");
    return true;
}

bool pj_save_store(PJ *p) {
    if (!p->sys || !p->recs) return false;
    for (int i = 0; i < SYS_GLOBALS && i < PJ_GLOBALS; i++) wr32(p->sys + SYS_GLOBALS_AT + 4 * i, (u32)p->g[i]);
    bool ok = store_file(p, "syssave.dat", p->sys, p->sysSize);
    return store_file(p, "syssvpo.dat", p->recs, p->recsSize) && ok;
}
