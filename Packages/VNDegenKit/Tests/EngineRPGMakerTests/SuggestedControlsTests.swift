import Foundation
import TestSupport
import Testing
import VNCore
@testable import EngineRPGMaker

private func key(_ code: Int) -> ControlAction { .key(KeyboardKey(windowsKeyCode: code)!) }

private func plugin(_ name: String, _ parameters: [String: String] = [:], source: String = "") -> RPGMakerControls.Plugin {
    RPGMakerControls.Plugin(name: name, parameters: parameters, source: source)
}

@Test func messagePluginsPutSkipAutoAndHideOnTheButtonsTheGamepadLeavesFree() throws {
    let suggestion = try #require(RPGMakerControls.suggestion([
        plugin("MessageSkip", ["スキップキー": "S", "オートキー": "A"]),
        plugin("MessageWindowHidden", ["triggerButton": #"["右クリック"]"#]),
    ]))
    #expect(suggestion.buttons == [.r2: key(83), .l2: key(65), .view: .click(.secondary)])
    #expect(suggestion.labels == [.r2: "Skip", .l2: "Auto", .view: "Hide window"])
}

@Test func keysTheGamepadAlreadyReachesAreLeftAlone() {
    #expect(RPGMakerControls.suggestion([
        plugin("MessageSkip", ["SkipKey": "shift", "AutoKey": "shift"]),
        plugin("MessageWindowHidden", ["triggerButton": #"["右クリック","shift"]"#]),
        plugin("UTA_MessageSkip", ["Skip Key": "pagedown"]),
    ]) == nil)
}

@Test func controlAndTabAreKeysNoButtonSendsToday() throws {
    let suggestion = try #require(RPGMakerControls.suggestion([
        plugin("triacontane/UTA_MessageSkip", ["Skip Key": "control"]),
        plugin("MessageWindowHidden", ["triggerButton": #"["tab"]"#]),
    ]))
    #expect(suggestion.buttons == [.r2: key(17), .view: key(9)])
}

@Test func literalKeysFromPluginsFillTheRestAndDeveloperKeysDont() throws {
    let suggestion = try #require(RPGMakerControls.suggestion([
        plugin("TMCommonEventKey", ["commonKeyH": "3", "commonKeyF9": "4", "commonKey0": "0"]),
        plugin("SaveWindow", source: "Input.keyMapper[76] = 'L';\nInput.keyMapper[90] = 'ok';"),
        plugin("GraphicalDesignMode", source: "Input.keyMapper[83] = 'save';"),
        plugin("DragSpine", source: "Input.keyMapper[67] = 'copy';"),
        plugin("PadPlus", source: "Input.gamepadMapper[6] = 'shortcut';\nInput.keyMapper[81] = 'shortcut';"),
    ]))
    #expect(suggestion.buttons == [.r2: key(72), .view: key(76)])
}

@Test func aGameWithItsOwnPadConfigurationGetsNothing() {
    #expect(RPGMakerControls.suggestion([
        plugin("MessageSkip", ["SkipKey": "S", "AutoKey": "A"]),
        plugin("Mano_InputConfig"),
    ]) == nil)
}

@Test func onlyPluginsTheGameTurnsOnCount() throws {
    let text = """
        // Generated by RPG Maker.
        var $plugins =
        [
        {"name":"MessageSkip","status":true,"description":"","parameters":{"SkipKey":"S","AutoKey":"A"}},
        {"name":"Mano_InputConfig","status":false,"description":"","parameters":{}},
        {"name":"TMCommonEventKey","status":true,"description":"","parameters":{"commonKeyM":"12"}}
        ];
        """
    let plugins = RPGMakerControls.enabledPlugins(text)
    #expect(plugins.map(\.name) == ["MessageSkip", "TMCommonEventKey"])
    let suggestion = try #require(RPGMakerControls.suggestion(plugins))
    #expect(suggestion.buttons == [.r2: key(83), .l2: key(65), .view: key(77)])
}

@Test func thePluginReadsTheGamesPluginFiles() throws {
    let root = TestFolders.root.appendingPathComponent("rpgmaker-suggest-\(UUID().uuidString)", isDirectory: true)
    defer { try? FileManager.default.removeItem(at: root) }
    let js = root.appendingPathComponent("www/js", isDirectory: true)
    try FileManager.default.createDirectory(at: js.appendingPathComponent("plugins"), withIntermediateDirectories: true)
    try Data("// rpg_core".utf8).write(to: js.appendingPathComponent("rpg_core.js"))
    try Data(#"var $plugins = [{"name":"Letters","status":true,"description":"","parameters":{}}];"#.utf8)
        .write(to: js.appendingPathComponent("plugins.js"))
    try Data("Input.keyMapper[72] = 'help';".utf8).write(to: js.appendingPathComponent("plugins/Letters.js"))
    let suggestion = try #require(RPGMakerPlugin(.mv).suggestedControls(folder: root))
    #expect(suggestion.buttons == [.r2: key(72)])
}
